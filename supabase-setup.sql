-- Run this in Supabase Dashboard > SQL Editor.
-- This assumes your Supabase Auth admin user already exists.
create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.messages add column if not exists created_at timestamptz not null default now();
alter table public.messages enable row level security;

grant insert on table public.messages to anon, authenticated;
grant select, delete on table public.messages to authenticated;
grant usage, select on sequence public.messages_id_seq to anon, authenticated;

drop policy if exists "Anyone can submit contact messages" on public.messages;
create policy "Anyone can submit contact messages"
on public.messages for insert
to anon, authenticated
with check (true);

drop policy if exists "Admin can view messages" on public.messages;
create policy "Admin can view messages"
on public.messages for select
to authenticated
using (auth.uid() = 'c29f6e85-0171-4c7d-9e03-7d5d969fe788'::uuid);

drop policy if exists "Admin can delete messages" on public.messages;
create policy "Admin can delete messages"
on public.messages for delete
to authenticated
using (auth.uid() = 'c29f6e85-0171-4c7d-9e03-7d5d969fe788'::uuid);
